// Generates supabase/seed_content.sql: the step ids certificates require + the resource catalog.
// Run from app/: node scripts/gen-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const floorsDir = resolve(here, '../src/content/floors')
const out = resolve(here, '../../supabase/seed_content.sql')

const stepIds = []
for (const f of readdirSync(floorsDir).filter((n) => /^floor\d+\.ts$/.test(n)).sort((a, b) => parseInt(a.slice(5)) - parseInt(b.slice(5)))) {
  const src = readFileSync(resolve(floorsDir, f), 'utf8')
  for (const m of src.matchAll(/\bid:\s*["'`](f\d+-s\d+)["'`]/g)) stepIds.push(m[1])
}

const resources = JSON.parse(readFileSync(resolve(here, '../src/data/resources.json'), 'utf8'))
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${(a ?? []).map(q).join(',')}]::text[]`

const sql = `-- Generated by app/scripts/gen-seed.mjs. Do not edit by hand.
-- Required steps for issue_certificate()
delete from public.required_steps where step_id not in (${stepIds.map(q).join(',')});
insert into public.required_steps (step_id) values
${stepIds.map((s) => `  (${q(s)})`).join(',\n')}
on conflict do nothing;

-- Resource catalog (${resources.length} rows)
insert into public.resources (id, title, url, provider, type, cost, level, skills, est_hours, summary, youtube_id, dead, verified_at) values
${resources
  .map((r) => `  (${[q(r.id), q(r.title), q(r.url), q(r.provider), q(r.type), q(r.cost), q(r.level), arr(r.skills), q(r.est_hours), q(r.summary), q(r.youtube_id), q(!!r.dead), q(r.verified_at)].join(', ')})`)
  .join(',\n')}
on conflict (id) do update set title = excluded.title, url = excluded.url, provider = excluded.provider, type = excluded.type, cost = excluded.cost,
  level = excluded.level, skills = excluded.skills, est_hours = excluded.est_hours, summary = excluded.summary, youtube_id = excluded.youtube_id,
  dead = excluded.dead, verified_at = excluded.verified_at;
`
writeFileSync(out, sql)
console.log(`[gen-seed] ${stepIds.length} required steps, ${resources.length} resources -> supabase/seed_content.sql`)
